// Generates src/lib/last-modified.ts: the last git commit date for the files
// behind each route, so sitemap.xml reports real content dates instead of the
// build time. Runs as `prebuild`; if git is unavailable the existing file is kept.
import { execSync } from "node:child_process";
import { readdirSync, existsSync, writeFileSync } from "node:fs";

const APP = "src/app";
const out = "src/lib/last-modified.ts";

function gitDate(files) {
  const existing = files.filter((f) => existsSync(f));
  if (!existing.length) return null;
  const raw = execSync(`git log -1 --format=%cI -- ${existing.map((f) => JSON.stringify(f)).join(" ")}`, {
    encoding: "utf8",
  }).trim();
  return raw || null;
}

let ok = true;
try {
  execSync("git rev-parse --is-inside-work-tree", { stdio: "ignore" });
} catch {
  ok = false;
}
if (!ok) {
  console.log("[last-modified] git not available; keeping existing file");
  process.exit(0);
}

const shared = {
  condition: ["src/lib/condition-details.ts", "src/components/condition-detail-template.tsx"],
  service: ["src/lib/service-details.ts", "src/components/service-detail-template.tsx"],
  location: ["src/lib/location-details.ts", "src/components/location-detail-template.tsx"],
  legal: ["src/components/legal-page.tsx"],
};
const kind = (route) => {
  if (route.startsWith("/locations/")) return "location";
  if (["/privacy", "/terms-of-use", "/hipaa-notice"].includes(route)) return "legal";
  return null;
};

// Walk src/app for page.tsx files (skip dynamic segments and the parked blog).
function walk(dir, prefix = "") {
  const routes = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (entry.name.startsWith("[") || entry.name === "blog") continue;
    const route = `${prefix}/${entry.name}`;
    const page = `${dir}/${entry.name}/page.tsx`;
    if (existsSync(page)) routes.push([route, page]);
    routes.push(...walk(`${dir}/${entry.name}`, route));
  }
  return routes;
}

const entries = [["/", `${APP}/page.tsx`], ...walk(APP)];
const conditionSlugs = new Set(
  (await import("../src/lib/conditions.ts").catch(() => ({ conditions: [] }))).conditions?.map((c) => c.slug) ?? []
);
const serviceSlugs = new Set(
  (await import("../src/lib/services.ts").catch(() => ({ services: [] }))).services?.map((s) => s.slug) ?? []
);

const map = {};
for (const [route, page] of entries) {
  const slug = route.slice(1);
  const extra =
    conditionSlugs.has(slug) ? shared.condition :
    serviceSlugs.has(slug) ? shared.service :
    kind(route) ? shared[kind(route)] : [];
  const date = gitDate([page, ...extra]);
  if (date) map[route] = date.slice(0, 10);
}

const body =
  `// Generated by scripts/last-modified.mjs — do not edit by hand.\n` +
  `// Last git commit date (YYYY-MM-DD) for the files behind each route.\n` +
  `export const lastModified: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;
writeFileSync(out, body);
console.log(`[last-modified] wrote ${Object.keys(map).length} routes to ${out}`);
